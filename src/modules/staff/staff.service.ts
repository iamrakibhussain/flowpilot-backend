import { prisma } from '../../database/prisma.js';
import { NotFoundError, BadRequestError } from '../../common/errors/app-error.js';
import { StaffStatus, StaffTier, Prisma } from '@prisma/client';
import {
  StaffItem,
  CreateStaffInput,
  UpdateStaffInput,
  StaffFilterQuery,
  StaffMetrics,
  StaffServiceItem,
} from './staff.types.js';

type StaffWithRelations = Prisma.StaffMemberGetPayload<{
  include: {
    services: { include: { service: true } };
    appointments: {
      select: {
        id: true;
        status: true;
        durationMinutes: true;
        service: { select: { price: true } };
      };
    };
  };
}>;

export class StaffService {
  private static readonly VALID_DAYS = ['MON', 'TUE', 'WED', 'THU', 'FRI', 'SAT', 'SUN'];
  private static readonly TIME_REGEX = /^([0-1]?[0-9]|2[0-3]):[0-5][0-9]$/;
  private static readonly EMAIL_REGEX = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

  private static validateInputFields(input: Partial<CreateStaffInput> | Partial<UpdateStaffInput>) {
    if (input.name !== undefined) {
      if (!input.name || input.name.trim().length === 0) {
        throw new BadRequestError('Staff member full name is required');
      }
      if (input.name.trim().length > 100) {
        throw new BadRequestError('Staff member full name cannot exceed 100 characters');
      }
    }

    if (input.roleTitle !== undefined) {
      if (!input.roleTitle || input.roleTitle.trim().length === 0) {
        throw new BadRequestError('Role or specialization title is required');
      }
      if (input.roleTitle.trim().length > 100) {
        throw new BadRequestError('Role title cannot exceed 100 characters');
      }
    }

    if (input.email) {
      const email = input.email.trim();
      if (email.length > 255 || !this.EMAIL_REGEX.test(email)) {
        throw new BadRequestError('Invalid email address format');
      }
    }

    if (input.phone) {
      if (input.phone.trim().length > 50) {
        throw new BadRequestError('Phone number cannot exceed 50 characters');
      }
    }

    if (input.hourlyRate !== undefined && input.hourlyRate !== null) {
      if (isNaN(input.hourlyRate) || input.hourlyRate < 0 || input.hourlyRate > 100000) {
        throw new BadRequestError('Hourly rate must be a non-negative number up to 100,000');
      }
    }

    if (input.commissionRate !== undefined && input.commissionRate !== null) {
      if (isNaN(input.commissionRate) || input.commissionRate < 0 || input.commissionRate > 100) {
        throw new BadRequestError('Commission rate must be between 0% and 100%');
      }
    }

    if (input.shiftStart && !this.TIME_REGEX.test(input.shiftStart)) {
      throw new BadRequestError('Shift start time must be in HH:mm format (e.g. 09:00)');
    }

    if (input.shiftEnd && !this.TIME_REGEX.test(input.shiftEnd)) {
      throw new BadRequestError('Shift end time must be in HH:mm format (e.g. 17:00)');
    }

    if (input.workingDays) {
      for (const day of input.workingDays) {
        if (!this.VALID_DAYS.includes(day)) {
          throw new BadRequestError(
            `Invalid working day: ${day}. Must be one of: ${this.VALID_DAYS.join(', ')}`,
          );
        }
      }
    }

    if (input.bio && input.bio.trim().length > 1000) {
      throw new BadRequestError('Bio cannot exceed 1000 characters');
    }
  }

  private static async validateServiceOwnership(
    organizationId: string,
    serviceIds: string[],
  ): Promise<string[]> {
    const distinctIds = Array.from(new Set(serviceIds.filter(Boolean)));
    if (distinctIds.length === 0) return [];

    const tenantServices = await prisma.service.findMany({
      where: {
        id: { in: distinctIds },
        organizationId,
      },
      select: { id: true },
    });

    if (tenantServices.length !== distinctIds.length) {
      throw new BadRequestError(
        'One or more selected services are invalid or do not belong to this organization',
      );
    }

    return distinctIds;
  }

  private static formatStaff(staff: StaffWithRelations): StaffItem {
    const services: StaffServiceItem[] = (staff.services || []).map((ss) => ({
      id: ss.service.id,
      name: ss.service.name,
      price: Number(ss.service.price),
      durationMinutes: ss.service.durationMinutes,
    }));

    // Calculate real revenue generated by completed appointments with this staff
    const completedAppointments = (staff.appointments || []).filter(
      (a) => a.status === 'COMPLETED' || a.status === 'CONFIRMED',
    );
    const revenueGenerated = completedAppointments.reduce((acc, a) => {
      const servicePrice = a.service?.price ? Number(a.service.price) : 0;
      return acc + servicePrice;
    }, 0);

    return {
      id: staff.id,
      organizationId: staff.organizationId,
      userId: staff.userId ?? null,
      name: staff.name,
      roleTitle: staff.roleTitle,
      email: staff.email ?? null,
      phone: staff.phone ?? null,
      initials: staff.initials,
      avatarBg: staff.avatarBg,
      status: staff.status,
      tier: staff.tier,
      hourlyRate: staff.hourlyRate ? Number(staff.hourlyRate) : null,
      commissionRate: staff.commissionRate ? Number(staff.commissionRate) : null,
      workingDays: staff.workingDays || ['MON', 'TUE', 'WED', 'THU', 'FRI'],
      shiftStart: staff.shiftStart || '09:00',
      shiftEnd: staff.shiftEnd || '17:00',
      bio: staff.bio ?? null,
      services,
      appointmentCount: staff.appointments?.length || 0,
      revenueGenerated,
      createdAt: staff.createdAt.toISOString(),
      updatedAt: staff.updatedAt.toISOString(),
    };
  }

  public static async listStaff(
    organizationId: string,
    filter?: StaffFilterQuery,
  ): Promise<StaffItem[]> {
    const where: Prisma.StaffMemberWhereInput = { organizationId };

    if (filter?.status) {
      where.status = filter.status;
    }

    if (filter?.tier) {
      where.tier = filter.tier;
    }

    if (filter?.serviceId) {
      where.services = {
        some: { serviceId: filter.serviceId },
      };
    }

    if (filter?.search && filter.search.trim().length > 0) {
      const q = filter.search.trim();
      where.OR = [
        { name: { contains: q, mode: 'insensitive' } },
        { roleTitle: { contains: q, mode: 'insensitive' } },
        { email: { contains: q, mode: 'insensitive' } },
      ];
    }

    const staff = await prisma.staffMember.findMany({
      where,
      include: {
        services: { include: { service: true } },
        appointments: {
          select: {
            id: true,
            status: true,
            durationMinutes: true,
            service: { select: { price: true } },
          },
        },
      },
      orderBy: { name: 'asc' },
    });

    return staff.map((s) => this.formatStaff(s as StaffWithRelations));
  }

  public static async getStaffById(
    organizationId: string,
    id: string,
  ): Promise<
    StaffItem & {
      recentAppointments: Array<{
        id: string;
        title: string;
        scheduledAt: string;
        durationMinutes: number;
        status: string;
        customerName: string;
        serviceName: string;
      }>;
    }
  > {
    const staff = await prisma.staffMember.findFirst({
      where: { id, organizationId },
      include: {
        services: { include: { service: true } },
        appointments: {
          include: {
            customer: { select: { name: true } },
            service: { select: { name: true, price: true } },
          },
          orderBy: { scheduledAt: 'desc' },
          take: 8,
        },
      },
    });

    if (!staff) {
      throw new NotFoundError('Staff member not found in this organization');
    }

    const formatted = this.formatStaff(staff as StaffWithRelations);
    const recentAppointments = (staff.appointments || []).map((a) => ({
      id: a.id,
      title: a.title,
      scheduledAt: a.scheduledAt.toISOString(),
      durationMinutes: a.durationMinutes,
      status: a.status,
      customerName: a.customer?.name || 'Walk-in Client',
      serviceName: a.service?.name || 'Standard Consultation',
    }));

    return {
      ...formatted,
      recentAppointments,
    };
  }

  public static async getMetrics(organizationId: string): Promise<StaffMetrics> {
    const allStaff = await prisma.staffMember.findMany({
      where: { organizationId },
      select: {
        id: true,
        status: true,
        appointments: {
          select: {
            id: true,
            status: true,
            service: { select: { price: true } },
          },
        },
      },
    });

    const totalStaff = allStaff.length;
    const availableStaff = allStaff.filter((s) => s.status === StaffStatus.AVAILABLE).length;
    const inSessionStaff = allStaff.filter((s) => s.status === StaffStatus.IN_SESSION).length;
    const onBreakStaff = allStaff.filter((s) => s.status === StaffStatus.ON_BREAK).length;
    const offlineStaff = allStaff.filter((s) => s.status === StaffStatus.OFFLINE).length;

    let totalAppointments = 0;
    let totalRevenueBilled = 0;

    for (const member of allStaff) {
      totalAppointments += member.appointments.length;
      for (const app of member.appointments) {
        if (app.status === 'COMPLETED' || app.status === 'CONFIRMED') {
          totalRevenueBilled += app.service?.price ? Number(app.service.price) : 0;
        }
      }
    }

    // Utilization rate: percentage of workforce either available or actively in session delivering client value
    const activeWorkforce = availableStaff + inSessionStaff;
    const utilizationRate =
      totalStaff > 0 ? Math.min(100, Math.round((activeWorkforce / totalStaff) * 100)) : 100;

    return {
      totalStaff,
      availableStaff,
      inSessionStaff,
      onBreakStaff,
      offlineStaff,
      totalAppointments,
      totalRevenueBilled,
      utilizationRate,
    };
  }

  public static async createStaff(
    organizationId: string,
    input: CreateStaffInput,
  ): Promise<StaffItem> {
    this.validateInputFields(input);

    const verifiedServiceIds =
      input.serviceIds && input.serviceIds.length > 0
        ? await this.validateServiceOwnership(organizationId, input.serviceIds)
        : [];

    const parts = input.name.trim().split(' ').filter(Boolean);
    const firstWord = parts[0] ?? '';
    const lastWord = parts[parts.length - 1] ?? '';
    const initials =
      parts.length > 1 && firstWord && lastWord
        ? `${firstWord[0] ?? ''}${lastWord[0] ?? ''}`.toUpperCase()
        : input.name.trim().slice(0, 2).toUpperCase();

    const avatarBgs = [
      'bg-blue-600',
      'bg-indigo-600',
      'bg-violet-600',
      'bg-purple-600',
      'bg-rose-600',
      'bg-amber-600',
      'bg-emerald-600',
      'bg-cyan-600',
    ];
    const avatarBg = input.avatarBg ?? avatarBgs[Math.floor(Math.random() * avatarBgs.length)];

    const created = await prisma.staffMember.create({
      data: {
        organizationId,
        name: input.name.trim(),
        roleTitle: input.roleTitle.trim(),
        email: input.email?.trim() || null,
        phone: input.phone?.trim() || null,
        initials,
        avatarBg,
        status: input.status ?? StaffStatus.AVAILABLE,
        tier: input.tier ?? StaffTier.FULL_TIME,
        hourlyRate: input.hourlyRate != null ? new Prisma.Decimal(input.hourlyRate) : null,
        commissionRate:
          input.commissionRate != null ? new Prisma.Decimal(input.commissionRate) : null,
        workingDays: input.workingDays || ['MON', 'TUE', 'WED', 'THU', 'FRI'],
        shiftStart: input.shiftStart || '09:00',
        shiftEnd: input.shiftEnd || '17:00',
        bio: input.bio?.trim() || null,
        services:
          verifiedServiceIds.length > 0
            ? {
                create: verifiedServiceIds.map((serviceId) => ({ serviceId })),
              }
            : undefined,
      },
      include: {
        services: { include: { service: true } },
        appointments: {
          select: {
            id: true,
            status: true,
            durationMinutes: true,
            service: { select: { price: true } },
          },
        },
      },
    });

    return this.formatStaff(created as StaffWithRelations);
  }

  public static async updateStaff(
    organizationId: string,
    id: string,
    input: UpdateStaffInput,
  ): Promise<StaffItem> {
    const existing = await prisma.staffMember.findFirst({
      where: { id, organizationId },
    });

    if (!existing) {
      throw new NotFoundError('Staff member not found in this organization');
    }

    this.validateInputFields(input);

    let verifiedServiceIds: string[] | undefined = undefined;
    if (input.serviceIds !== undefined) {
      verifiedServiceIds = await this.validateServiceOwnership(organizationId, input.serviceIds);
    }

    const data: Prisma.StaffMemberUpdateInput = {};

    if (input.name !== undefined) {
      data.name = input.name.trim();
      const parts = input.name.trim().split(' ').filter(Boolean);
      const firstWord = parts[0] ?? '';
      const lastWord = parts[parts.length - 1] ?? '';
      data.initials =
        parts.length > 1 && firstWord && lastWord
          ? `${firstWord[0] ?? ''}${lastWord[0] ?? ''}`.toUpperCase()
          : input.name.trim().slice(0, 2).toUpperCase();
    }

    if (input.roleTitle !== undefined) data.roleTitle = input.roleTitle.trim();
    if (input.email !== undefined) data.email = input.email?.trim() || null;
    if (input.phone !== undefined) data.phone = input.phone?.trim() || null;
    if (input.avatarBg !== undefined) data.avatarBg = input.avatarBg;
    if (input.status !== undefined) data.status = input.status;
    if (input.tier !== undefined) data.tier = input.tier;
    if (input.hourlyRate !== undefined) {
      data.hourlyRate = input.hourlyRate != null ? new Prisma.Decimal(input.hourlyRate) : null;
    }
    if (input.commissionRate !== undefined) {
      data.commissionRate =
        input.commissionRate != null ? new Prisma.Decimal(input.commissionRate) : null;
    }
    if (input.workingDays !== undefined) data.workingDays = input.workingDays;
    if (input.shiftStart !== undefined) data.shiftStart = input.shiftStart;
    if (input.shiftEnd !== undefined) data.shiftEnd = input.shiftEnd;
    if (input.bio !== undefined) data.bio = input.bio?.trim() || null;

    const updated = await prisma.$transaction(async (tx) => {
      if (verifiedServiceIds !== undefined) {
        await tx.staffService.deleteMany({
          where: { staffMemberId: id },
        });

        if (verifiedServiceIds.length > 0) {
          await tx.staffService.createMany({
            data: verifiedServiceIds.map((serviceId) => ({
              staffMemberId: id,
              serviceId,
            })),
          });
        }
      }

      return tx.staffMember.update({
        where: { id },
        data,
        include: {
          services: { include: { service: true } },
          appointments: {
            select: {
              id: true,
              status: true,
              durationMinutes: true,
              service: { select: { price: true } },
            },
          },
        },
      });
    });

    return this.formatStaff(updated as StaffWithRelations);
  }

  public static async updateStatus(
    organizationId: string,
    id: string,
    status: StaffStatus,
  ): Promise<StaffItem> {
    const existing = await prisma.staffMember.findFirst({
      where: { id, organizationId },
    });

    if (!existing) {
      throw new NotFoundError('Staff member not found in this organization');
    }

    const updated = await prisma.staffMember.update({
      where: { id },
      data: { status },
      include: {
        services: { include: { service: true } },
        appointments: {
          select: {
            id: true,
            status: true,
            durationMinutes: true,
            service: { select: { price: true } },
          },
        },
      },
    });

    return this.formatStaff(updated as StaffWithRelations);
  }

  public static async deleteStaff(
    organizationId: string,
    id: string,
  ): Promise<{ success: boolean; unassignedAppointmentsCount: number }> {
    const existing = await prisma.staffMember.findFirst({
      where: { id, organizationId },
      include: {
        appointments: {
          where: {
            scheduledAt: { gte: new Date() },
            status: { in: ['CONFIRMED', 'PENDING'] },
          },
        },
      },
    });

    if (!existing) {
      throw new NotFoundError('Staff member not found in this organization');
    }

    const unassignedCount = existing.appointments.length;

    await prisma.$transaction(async (tx) => {
      // Safely unassign any pending or confirmed upcoming appointments strictly within this tenant
      if (unassignedCount > 0) {
        await tx.appointment.updateMany({
          where: { staffMemberId: id, organizationId },
          data: { staffMemberId: null },
        });
      }

      await tx.staffService.deleteMany({
        where: { staffMemberId: id },
      });

      await tx.staffMember.delete({
        where: { id },
      });
    });

    return {
      success: true,
      unassignedAppointmentsCount: unassignedCount,
    };
  }
}
